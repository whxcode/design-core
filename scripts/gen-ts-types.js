#!/usr/bin/env node

const fs = require("fs");
const path = require("path");

const rootDir = path.resolve(__dirname, "..");

const mappings = [
  {
    input: "z-editor/include/ui-event/z-ui-event.h",
    output: "z-types/ui-event/z-ui-event.ts",
  },
];

const typeMap = new Map([
  ["bool", "boolean"],
  ["char", "number"],
  ["short", "number"],
  ["int", "number"],
  ["long", "number"],
  ["size_t", "number"],
  ["uintptr_t", "number"],
  ["uint8_t", "number"],
  ["uint16_t", "number"],
  ["uint32_t", "number"],
  ["uint64_t", "number"],
  ["int8_t", "number"],
  ["int16_t", "number"],
  ["int32_t", "number"],
  ["int64_t", "number"],
  ["float", "number"],
  ["double", "number"],
  ["std::string", "string"],
  ["string", "string"],
]);

function stripComments(source) {
  return source.replace(/\/\*[\s\S]*?\*\//g, "").replace(/\/\/.*$/gm, "");
}

function normalizeType(type) {
  return type.replace(/\bconst\b/g, "").replace(/[&*]/g, "").trim();
}

function toTsType(type) {
  const normalized = normalizeType(type);
  return typeMap.get(normalized) ?? normalized;
}

function parseEnumClasses(source) {
  const enums = [];
  const enumRegex = /enum\s+class\s+(\w+)\s*(?::\s*[\w:]+)?\s*\{([\s\S]*?)\}\s*;/g;

  for (const match of source.matchAll(enumRegex)) {
    const [, name, body] = match;
    const values = body
      .split(",")
      .map((item) => item.trim())
      .filter(Boolean)
      .map((item) => item.split("=")[0].trim())
      .map(stripZPrefix)
      .filter(Boolean);

    enums.push({ name, values });
  }

  return enums;
}

function stripZPrefix(name) {
  if (/^z[A-Z]/.test(name)) {
    return name.slice(1);
  }

  return name;
}

function parseStructs(source) {
  const structs = [];
  const normalizedSource = source.replace(
    /(\b[A-Za-z_][\w:<>]*\s+[A-Za-z_]\w*)\s*\{[^;{}]*\}\s*;/g,
    "$1;",
  );
  const structRegex = /struct\s+(\w+)\s*\{([\s\S]*?)\}\s*;/g;

  for (const match of normalizedSource.matchAll(structRegex)) {
    const [, name, body] = match;
    const fields = [];
    const fieldRegex = /^\s*([A-Za-z_][\w:<>]*)\s+([A-Za-z_]\w*)\s*(?:\{[^;]*\}|=[^;]*)?\s*;/gm;

    for (const fieldMatch of body.matchAll(fieldRegex)) {
      const [, cppType, fieldName] = fieldMatch;
      fields.push({
        name: fieldName,
        type: toTsType(cppType),
      });
    }

    structs.push({ name, fields });
  }

  return structs;
}

function emitTs(enums, structs, input) {
  const lines = [
    "// Auto-generated by design-core/scripts/gen-ts-types.js.",
    `// Source: ${input}`,
    "",
  ];

  for (const item of enums) {
    lines.push(`export enum ${item.name} {`);
    item.values.forEach((value, index) => {
      lines.push(`  ${value} = ${index},`);
    });
    lines.push("}");
    lines.push("");
  }

  for (const item of structs) {
    lines.push(`export interface ${item.name} {`);
    for (const field of item.fields) {
      lines.push(`  ${field.name}: ${field.type};`);
    }
    lines.push("}");
    lines.push("");
  }

  return `${lines.join("\n").trimEnd()}\n`;
}

function generate(mapping) {
  const inputPath = path.resolve(rootDir, mapping.input);
  const outputPath = path.resolve(rootDir, mapping.output);
  const source = stripComments(fs.readFileSync(inputPath, "utf8"));
  const enums = parseEnumClasses(source);
  const structs = parseStructs(source);
  const output = emitTs(enums, structs, mapping.input);

  fs.mkdirSync(path.dirname(outputPath), { recursive: true });
  fs.writeFileSync(outputPath, output);
  console.log(`${mapping.input} -> ${mapping.output}`);
}

for (const mapping of mappings) {
  generate(mapping);
}
